describe('Tests login', () => {
  it('login - success', () => {
    cy.visit('https://practicetestautomation.com/practice-test-login/?utm_source=chatgpt.com')
    cy.get('[name="username"]').type('student')
    cy.get('[name="password"]').type('Password123')
    cy.get('#submit').click()
    cy.url().should('include', '/logged-in-successfully/')
    cy.contains('Logged In Successfully').should('be.visible')
    cy.contains('Log out').should('be.visible')
  })
  it('Negative username test', () => {
    cy.visit('https://practicetestautomation.com/practice-test-login/?utm_source=chatgpt.com')
    cy.get('[name="username"]').type('incorrectUser')
    cy.get('[name="password"]').type('Password123')
    cy.get('#submit').click()
    cy.url().should('include', '/practice-test-login/')
    cy.contains('Your username is invalid!').should('be.visible')
  })
  it('Negative password test', () => {
    cy.visit('https://practicetestautomation.com/practice-test-login/?utm_source=chatgpt.com')
    cy.get('[name="username"]').type('student')
    cy.get('[name="password"]').type('incorrectPassword')
    cy.get('#submit').click()
    cy.url().should('include', '/practice-test-login/')
    cy.contains('Your password is invalid!').should('be.visible')
  })
  it('Login - success and log out', () => {
    cy.visit('https://practicetestautomation.com/practice-test-login/?utm_source=chatgpt.com')
    cy.get('[name="username"]').type('student')
    cy.get('[name="password"]').type('Password123')
    cy.get('#submit').click()
    cy.url().should('include', '/logged-in-successfully/')
    cy.contains('Logged In Successfully').should('be.visible')
    cy.contains('Log out').should('be.visible')
    cy.get('.wp-block-button__link').click()
})
it('Empty username test', () => {
    cy.visit('https://practicetestautomation.com/practice-test-login/?utm_source=chatgpt.com')
    cy.get('[name="username"]')
    cy.get('[name="password"]').type('Password123')
    cy.get('#submit').click()
    cy.url().should('include', '/practice-test-login/')
    cy.contains('Your username is invalid!').should('be.visible')
})
it('Empty password test', () => {
    cy.visit('https://practicetestautomation.com/practice-test-login/?utm_source=chatgpt.com')
    cy.get('[name="username"]').type('student')
    cy.get('[name="password"]')
    cy.get('#submit').click()
    cy.url().should('include', '/practice-test-login/')
    cy.contains('Your password is invalid!').should('be.visible')
})
})